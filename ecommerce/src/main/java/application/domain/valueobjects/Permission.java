package application.domain.valueobjects;

import java.util.Arrays;
import java.util.EnumSet;
import java.util.Set;

import static application.domain.valueobjects.UserRole.ADMINISTRATOR;
import static application.domain.valueobjects.UserRole.BUYER;
import static application.domain.valueobjects.UserRole.LOGISTICS_OPERATOR;
import static application.domain.valueobjects.UserRole.SELLER;
import static application.domain.valueobjects.UserRole.SUPERVISOR;

/**
 * Operation a user may be allowed to execute. Each value lists the roles that may perform it.
 * Ownership restrictions (a buyer only sees its own orders, ...) are enforced separately by
 * ValidateResourceAccessService.
 */
public enum Permission {
    // User management
    USER_REGISTER(ADMINISTRATOR),
    USER_CONSULT(BUYER, SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    USER_UPDATE(BUYER, SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    USER_CHANGE_STATUS(ADMINISTRATOR),
    // Buyers
    BUYER_UPDATE(BUYER, ADMINISTRATOR),
    BUYER_CHANGE_COMMERCIAL_STATUS(ADMINISTRATOR),
    BUYER_CONSULT(BUYER, ADMINISTRATOR, SUPERVISOR),
    // Sellers
    SELLER_REGISTER(ADMINISTRATOR),
    SELLER_CONSULT(SELLER, ADMINISTRATOR, SUPERVISOR),
    SELLER_UPDATE(ADMINISTRATOR),
    SELLER_CHANGE_STATUS(ADMINISTRATOR),
    // Warehouses
    WAREHOUSE_REGISTER(ADMINISTRATOR),
    WAREHOUSE_CONSULT(SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    WAREHOUSE_UPDATE(ADMINISTRATOR),
    WAREHOUSE_CHANGE_STATUS(ADMINISTRATOR),
    // Catalog
    PRODUCT_REGISTER(SELLER),
    PRODUCT_UPDATE(SELLER),
    PRODUCT_PUBLISH(SELLER, ADMINISTRATOR),
    PRODUCT_SUSPEND(SELLER, ADMINISTRATOR),
    PRODUCT_DISCONTINUE(SELLER, ADMINISTRATOR),
    PRODUCT_CONSULT(BUYER, SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    // Inventory
    INVENTORY_REGISTER_INITIAL(SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_REGISTER_ENTRY(SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_RESERVE(ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_REGISTER_SALE_DISPATCH(ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_ADJUST(SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_REGISTER_RETURN(ADMINISTRATOR, LOGISTICS_OPERATOR),
    INVENTORY_CONSULT(SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    // Cart
    CART_MANAGE(BUYER),
    CART_CONSULT(BUYER),
    // Orders
    ORDER_CREATE(BUYER),
    ORDER_VALIDATE_PAYMENT(BUYER, ADMINISTRATOR),
    ORDER_UPDATE_STATUS(BUYER, ADMINISTRATOR),
    ORDER_CONSULT(BUYER, SELLER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    // Billing
    INVOICE_GENERATE(BUYER, ADMINISTRATOR),
    INVOICE_CONSULT(BUYER, ADMINISTRATOR, SUPERVISOR),
    // Logistics
    SHIPMENT_PREPARE(ADMINISTRATOR, LOGISTICS_OPERATOR),
    SHIPMENT_DISPATCH(ADMINISTRATOR, LOGISTICS_OPERATOR),
    SHIPMENT_CONFIRM_DELIVERY(ADMINISTRATOR, LOGISTICS_OPERATOR),
    SHIPMENT_CONSULT(BUYER, ADMINISTRATOR, LOGISTICS_OPERATOR, SUPERVISOR),
    // Returns and refunds
    RETURN_REQUEST(BUYER),
    RETURN_RECEIVE(ADMINISTRATOR, LOGISTICS_OPERATOR),
    REFUND_GENERATE(ADMINISTRATOR),
    REFUND_APPROVE(ADMINISTRATOR),
    REFUND_REJECT(ADMINISTRATOR),
    // Reporting and audit
    REPORT_CONSULT(ADMINISTRATOR, SUPERVISOR),
    AUDIT_CONSULT(ADMINISTRATOR, SUPERVISOR);

    private final Set<UserRole> allowedRoles;

    Permission(UserRole... roles) {
        this.allowedRoles = EnumSet.copyOf(Arrays.asList(roles));
    }

    public boolean isAllowedFor(UserRole role) {
        return allowedRoles.contains(role);
    }
}
